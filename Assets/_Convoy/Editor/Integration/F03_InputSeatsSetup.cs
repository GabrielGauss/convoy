using System.Collections.Generic;
using System.IO;
using Convoy.Crew;
using Convoy.Input;
using Convoy.Vehicle;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.InputSystem;
using UnityEngine.SceneManagement;

namespace Convoy.Editor
{
    /// <summary>
    /// F-03c integration (spec docs/specs/F-03-input-seats.md, ADR-002, D-030): wires the F-03b per-seat input onto the
    /// crew Jackal so the vehicle no longer reads the keyboard directly.
    ///
    /// What it does (idempotent, never deletes anything):
    ///   1. creates <c>InputSeatConfig.asset</c>, <c>Crew_Config.asset</c> and <c>PlayerSlot.prefab</c> when missing;
    ///   2. on the Jackal's prefab asset: adds <see cref="VehicleSeats"/> (config = Crew_Config) and DISABLES
    ///      <see cref="PilotInputSource"/> (kept, not removed, until Gabriel approves deleting it);
    ///   3. in the Jackal's scene: creates a root <c>CrewInput</c> object with <see cref="PlayerInputManager"/> +
    ///      <see cref="SeatInputRouter"/> pointing at the Jackal's VehicleSeats.
    ///
    /// Why an editor script instead of hand wiring: scenes/prefabs are generated by versioned scripts (tasks README),
    /// and the orchestrator runs this in the single Unity Editor. Re-running only fills what is missing; references a
    /// human has already set are never overwritten.
    /// </summary>
    public static class F03_InputSeatsSetup
    {
        public const string SandboxScenePath = "Assets/_Convoy/Scenes/Sandbox.unity";
        public const string Sprint01ScenePath = "Assets/_Convoy/Scenes/Sprint_01.unity";
        public const string Paramo01ScenePath = "Assets/_Convoy/Scenes/Paramo_01.unity";

        public const string JackalPrefabPath = "Assets/_Convoy/Prefabs/Jackal.prefab";
        public const string ControlsPath = "Assets/_Convoy/Config/Input/ConvoyControls.inputactions";
        public const string InputSeatConfigPath = "Assets/_Convoy/Config/Input/InputSeatConfig.asset";
        public const string CrewConfigPath = "Assets/_Convoy/Config/Crew_Config.asset";
        public const string PlayerSlotPath = "Assets/_Convoy/Prefabs/Input/PlayerSlot.prefab";
        public const string CrewInputName = "CrewInput";

        // Spec: one device set per seat, so at most Pilot + Gunner + Engineer.
        private const int MaxPlayers = 3;

        private static readonly string[] MenuScenes = { SandboxScenePath, Sprint01ScenePath, Paramo01ScenePath };

        [MenuItem("Convoy/Integration/F-03 Input Seats Setup")]
        public static void ApplyToAllScenes()
        {
            // Why: opening a scene in Single mode unloads the current one; let a human save first (no-op if clean).
            if (!Application.isBatchMode && !EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            {
                Debug.LogWarning("[F-03c] Cancelled: unsaved scene changes were not resolved.");
                return;
            }
            foreach (string path in MenuScenes) ApplyToScene(path);
        }

        /// <summary>
        /// D-030 entry point: opens <paramref name="scenePath"/>, wires crew input onto its Jackal and saves the scene.
        /// Missing scenes are skipped with a warning (so LV/TR tasks can call it before their scene exists).
        /// </summary>
        public static void ApplyToScene(string scenePath)
        {
            if (!File.Exists(scenePath))
            {
                Debug.LogWarning($"[F-03c] {scenePath} not found: skipped.");
                return;
            }

            Scene scene = SceneManager.GetActiveScene();
            if (!(scene.IsValid() && scene.isLoaded && scene.path == scenePath))
                scene = EditorSceneManager.OpenScene(scenePath, OpenSceneMode.Single);

            GameObject jackal = FindCrewVehicle(scene);
            if (jackal == null) return;   // FindCrewVehicle logged why

            var report = new Report();
            Configure(jackal, report);

            if (report.Changes > 0)
            {
                EditorSceneManager.MarkSceneDirty(scene);
                if (!EditorSceneManager.SaveScene(scene, scenePath))
                {
                    Debug.LogError($"[F-03c] Could not save {scenePath}.");
                    return;
                }
                AssetDatabase.SaveAssets();
            }
            Debug.Log($"[F-03c] {scenePath}: {report.Summary()}");
        }

        /// <summary>
        /// Configures one Jackal GameObject (prefab instance or plain object) in an open scene for crew input, and
        /// ensures the scene's CrewInput rig. Does NOT save the scene: the caller does (ParamoTerrainGenerator calls
        /// this from its player-rig step and then saves). Returns true when the Jackal ends up fully wired.
        /// </summary>
        public static bool ConfigureJackal(GameObject jackal)
        {
            if (jackal == null)
            {
                Debug.LogError("[F-03c] ConfigureJackal: no Jackal given.");
                return false;
            }
            var report = new Report();
            bool ok = Configure(jackal, report);
            if (report.Changes > 0) EditorSceneManager.MarkSceneDirty(jackal.scene);
            Debug.Log($"[F-03c] {jackal.name} in {jackal.scene.path}: {report.Summary()}");
            return ok;
        }

        // ================================================================== core

        private static bool Configure(GameObject jackal, Report report)
        {
            InputActionAsset controls = AssetDatabase.LoadAssetAtPath<InputActionAsset>(ControlsPath);
            if (controls == null)
            {
                report.Error($"{ControlsPath} missing (F-03b)");
                return false;
            }
            InputSeatConfig seatConfig = LoadOrCreate<InputSeatConfig>(InputSeatConfigPath, report);
            CrewConfig crewConfig = LoadOrCreate<CrewConfig>(CrewConfigPath, report);
            GameObject playerSlot = EnsurePlayerSlot(controls, report);
            if (playerSlot == null) return false;

            // The canonical prefab is always fixed (spec step 3), plus the instance's own source prefab if different
            // (e.g. a future variant), so every scene using the Jackal stops reading the keyboard.
            EnsureVehiclePrefab(JackalPrefabPath, crewConfig, report);
            string sourcePath = PrefabUtility.GetPrefabAssetPathOfNearestInstanceRoot(jackal);
            if (!string.IsNullOrEmpty(sourcePath) && sourcePath != JackalPrefabPath)
                EnsureVehiclePrefab(sourcePath, crewConfig, report);

            VehicleSeats seats = EnsureInstance(jackal, crewConfig, report);
            if (seats == null) return false;

            EnsureCrewInput(jackal.scene, seats, seatConfig, playerSlot, report);
            return report.Errors == 0;
        }

        /// <summary>Spec: "the one VehicleController in the scene". Prefers a root named Jackal so later AI rivals
        /// (also Jackals, A-01c) don't make it ambiguous.</summary>
        private static GameObject FindCrewVehicle(Scene scene)
        {
            var found = new List<VehicleController>();
            foreach (GameObject root in scene.GetRootGameObjects())
            {
                var named = root.name == "Jackal" ? root.GetComponentInChildren<VehicleController>(true) : null;
                if (named != null) return named.gameObject;
                found.AddRange(root.GetComponentsInChildren<VehicleController>(true));
            }
            if (found.Count == 1) return found[0].gameObject;
            Debug.LogError($"[F-03c] {scene.path}: expected one crew VehicleController (or a root named 'Jackal'), " +
                           $"found {found.Count}. Nothing changed.");
            return null;
        }

        // ================================================================== assets

        private static T LoadOrCreate<T>(string path, Report report) where T : ScriptableObject
        {
            var asset = AssetDatabase.LoadAssetAtPath<T>(path);
            if (asset != null) return asset;
            // New assets start from the code defaults (= PilotInputSource's numbers for InputSeatConfig); after that
            // the asset is the source of truth and is never overwritten here.
            EnsureFolder(Path.GetDirectoryName(path));
            asset = ScriptableObject.CreateInstance<T>();
            AssetDatabase.CreateAsset(asset, path);
            report.Change($"created {Path.GetFileName(path)}");
            return asset;
        }

        private static GameObject EnsurePlayerSlot(InputActionAsset controls, Report report)
        {
            var existing = AssetDatabase.LoadAssetAtPath<GameObject>(PlayerSlotPath);
            if (existing != null)
            {
                // Only repair an unassigned actions field; any other human tweak to the prefab is left alone.
                var input = existing.GetComponent<PlayerInput>();
                if (input != null && input.actions != null) return existing;

                GameObject contents = PrefabUtility.LoadPrefabContents(PlayerSlotPath);
                try
                {
                    var pi = contents.GetComponent<PlayerInput>();
                    if (pi == null) pi = contents.AddComponent<PlayerInput>();
                    ConfigurePlayerInput(pi, controls, report);
                    PrefabUtility.SaveAsPrefabAsset(contents, PlayerSlotPath);
                }
                finally { PrefabUtility.UnloadPrefabContents(contents); }
                report.Change("repaired PlayerSlot.prefab");
                return AssetDatabase.LoadAssetAtPath<GameObject>(PlayerSlotPath);
            }

            EnsureFolder(Path.GetDirectoryName(PlayerSlotPath));
            // Built in a preview scene so creating the prefab never adds/dirties anything in the open scene.
            Scene preview = EditorSceneManager.NewPreviewScene();
            try
            {
                var go = new GameObject("PlayerSlot");
                SceneManager.MoveGameObjectToScene(go, preview);
                ConfigurePlayerInput(go.AddComponent<PlayerInput>(), controls, report);
                GameObject saved = PrefabUtility.SaveAsPrefabAsset(go, PlayerSlotPath, out bool success);
                if (!success || saved == null)
                {
                    report.Error($"could not save {PlayerSlotPath}");
                    return null;
                }
                report.Change("created PlayerSlot.prefab");
                return saved;
            }
            finally { EditorSceneManager.ClosePreviewScene(preview); }
        }

        private static void ConfigurePlayerInput(PlayerInput input, InputActionAsset controls, Report report)
        {
            // Serialized properties instead of the C# setters: the setters touch live action state, which we don't
            // want in edit mode, and setting `actions` in the Inspector auto-fills a default map we must NOT have
            // (the router picks the seat map on join; a default map would enable Pilot for every pad).
            var so = new SerializedObject(input);
            SetRef(so, "m_Actions", controls, report, overwrite: true);
            SetEnum(so, "m_NotificationBehavior", (int)PlayerNotifications.InvokeCSharpEvents, report);
            SetString(so, "m_DefaultActionMap", string.Empty, report);
            SetRef(so, "m_Camera", null, report, overwrite: true);
            // Each player keeps the device set it joined with; without this a lone keyboard player could auto-switch
            // to a gamepad instead of that pad joining as the Gunner.
            SetBool(so, "m_NeverAutoSwitchControlSchemes", true, report);
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        /// <summary>Adds VehicleSeats and disables PilotInputSource on a vehicle prefab asset.</summary>
        private static void EnsureVehiclePrefab(string prefabPath, CrewConfig crewConfig, Report report)
        {
            var asset = AssetDatabase.LoadAssetAtPath<GameObject>(prefabPath);
            if (asset == null)
            {
                report.Error($"{prefabPath} missing");
                return;
            }
            if (IsVehicleWired(asset, crewConfig)) return;   // cheap read-only check: no prefab re-save when done

            // LoadPrefabContents edits the asset in isolation (like Prefab Mode) and SaveAsPrefabAsset writes it back
            // through Unity's serializer: the safe alternative to editing prefab YAML.
            GameObject contents = PrefabUtility.LoadPrefabContents(prefabPath);
            try
            {
                var vehicle = contents.GetComponentInChildren<VehicleController>(true);
                GameObject host = vehicle != null ? vehicle.gameObject : contents;
                var seats = host.GetComponent<VehicleSeats>();
                if (seats == null)
                {
                    seats = host.AddComponent<VehicleSeats>();
                    report.Change($"added VehicleSeats to {Path.GetFileName(prefabPath)}");
                }
                var so = new SerializedObject(seats);
                SetRef(so, "_config", crewConfig, report, overwrite: false);
                so.ApplyModifiedPropertiesWithoutUndo();

                foreach (var legacy in contents.GetComponentsInChildren<PilotInputSource>(true))
                {
                    if (!legacy.enabled) continue;
                    // Disabled, not removed (spec): Gabriel approves deleting it later; a disabled MonoBehaviour gets
                    // no Awake/Update, so it neither creates its InputActions nor drives the car (no double input).
                    legacy.enabled = false;
                    report.Change($"disabled PilotInputSource on {Path.GetFileName(prefabPath)}");
                }
                PrefabUtility.SaveAsPrefabAsset(contents, prefabPath);
            }
            finally { PrefabUtility.UnloadPrefabContents(contents); }
        }

        private static bool IsVehicleWired(GameObject root, CrewConfig crewConfig)
        {
            var seats = root.GetComponentInChildren<VehicleSeats>(true);
            if (seats == null) return false;
            var so = new SerializedObject(seats);
            if (so.FindProperty("_config")?.objectReferenceValue == null && crewConfig != null) return false;
            foreach (var legacy in root.GetComponentsInChildren<PilotInputSource>(true))
                if (legacy.enabled) return false;
            return true;
        }

        // ================================================================== scene

        /// <summary>Makes sure the scene instance has the prefab's changes and no override undoing them.</summary>
        private static VehicleSeats EnsureInstance(GameObject jackal, CrewConfig crewConfig, Report report)
        {
            bool isInstance = PrefabUtility.IsPartOfPrefabInstance(jackal);
            var seats = jackal.GetComponentInChildren<VehicleSeats>(true);
            if (seats == null && isInstance)
            {
                // Prefab instances normally pick up asset changes on the next editor update; force it now so the
                // router below can reference the instance's VehicleSeats in this same run.
                PrefabUtility.MergePrefabInstance(PrefabUtility.GetNearestPrefabInstanceRoot(jackal));
                seats = jackal.GetComponentInChildren<VehicleSeats>(true);
            }
            if (seats == null && !isInstance)
            {
                // A plain (unlinked) Jackal: wire it in place, same as the prefab.
                seats = jackal.AddComponent<VehicleSeats>();
                report.Change($"added VehicleSeats to scene object {jackal.name}");
            }
            if (seats == null)
            {
                report.Error($"{jackal.name}: VehicleSeats not present after prefab merge; re-run the menu item");
                return null;
            }

            var so = new SerializedObject(seats);
            SetRef(so, "_config", crewConfig, report, overwrite: false);
            if (so.ApplyModifiedPropertiesWithoutUndo() && isInstance)
                PrefabUtility.RecordPrefabInstancePropertyModifications(seats);

            // An instance override could re-enable the legacy input in one scene; that would be double input.
            foreach (var legacy in jackal.GetComponentsInChildren<PilotInputSource>(true))
            {
                if (!legacy.enabled) continue;
                legacy.enabled = false;
                if (isInstance) PrefabUtility.RecordPrefabInstancePropertyModifications(legacy);
                report.Change($"disabled PilotInputSource on scene {jackal.name}");
            }
            return seats;
        }

        private static void EnsureCrewInput(Scene scene, VehicleSeats seats, InputSeatConfig seatConfig,
                                            GameObject playerSlot, Report report)
        {
            SeatInputRouter router = null;
            foreach (GameObject root in scene.GetRootGameObjects())
            {
                router = root.GetComponentInChildren<SeatInputRouter>(true);
                if (router != null) break;
            }

            GameObject host;
            if (router != null)
            {
                host = router.gameObject;
            }
            else
            {
                host = FindRoot(scene, CrewInputName);
                if (host == null)
                {
                    host = new GameObject(CrewInputName);
                    SceneManager.MoveGameObjectToScene(host, scene);
                    report.Change($"created {CrewInputName}");
                }
            }

            // PlayerInputManager must be added before the router: the router serializes a reference to it.
            var manager = host.GetComponent<PlayerInputManager>();
            if (manager == null)
            {
                manager = host.AddComponent<PlayerInputManager>();
                report.Change("added PlayerInputManager");
                // Settings applied only on creation; afterwards the component belongs to whoever tunes it.
                var mso = new SerializedObject(manager);
                SetRef(mso, "m_PlayerPrefab", playerSlot, report, overwrite: true);
                SetEnum(mso, "m_NotificationBehavior", (int)PlayerNotifications.InvokeCSharpEvents, report);
                SetEnum(mso, "m_JoinBehavior", (int)PlayerJoinBehavior.JoinPlayersWhenButtonIsPressed, report);
                SetInt(mso, "m_MaxPlayerCount", MaxPlayers, report);
                SetBool(mso, "m_SplitScreen", false, report);   // per-seat cameras are C-01/G-01, not F-03
                mso.ApplyModifiedPropertiesWithoutUndo();
            }
            else
            {
                var mso = new SerializedObject(manager);
                SetRef(mso, "m_PlayerPrefab", playerSlot, report, overwrite: false);
                mso.ApplyModifiedPropertiesWithoutUndo();
            }

            if (router == null)
            {
                router = host.AddComponent<SeatInputRouter>();
                report.Change("added SeatInputRouter");
            }
            var rso = new SerializedObject(router);
            SetRef(rso, "_playerInputManager", manager, report, overwrite: false);
            SetRef(rso, "_vehicle", seats, report, overwrite: false);
            SetRef(rso, "_config", seatConfig, report, overwrite: false);
            rso.ApplyModifiedPropertiesWithoutUndo();

            Object wiredVehicle = rso.FindProperty("_vehicle")?.objectReferenceValue;
            if (wiredVehicle != seats)
                Debug.LogWarning($"[F-03c] {scene.path}: SeatInputRouter already drives '{wiredVehicle?.name}', not " +
                                 $"'{seats.name}'. Left as set by a human.", router);
        }

        // ================================================================== helpers

        private static GameObject FindRoot(Scene scene, string name)
        {
            foreach (GameObject go in scene.GetRootGameObjects())
                if (go.name == name) return go;
            return null;
        }

        /// <summary>Creates "Assets/a/b/c" folder by folder (AssetDatabase.CreateFolder makes one level at a time).</summary>
        private static void EnsureFolder(string assetFolder)
        {
            assetFolder = assetFolder?.Replace('\\', '/');
            if (string.IsNullOrEmpty(assetFolder) || AssetDatabase.IsValidFolder(assetFolder)) return;
            string parent = Path.GetDirectoryName(assetFolder)?.Replace('\\', '/');
            EnsureFolder(parent);
            AssetDatabase.CreateFolder(parent, Path.GetFileName(assetFolder));
        }

        // The Set* helpers write only when the value differs (so re-runs report 0 changes) and turn a missing
        // property into a loud error: Input System field names are internal and could change between versions.

        private static SerializedProperty Find(SerializedObject so, string name, Report report)
        {
            SerializedProperty p = so.FindProperty(name);
            if (p == null) report.Error($"{so.targetObject.GetType().Name}.{name} not found (package version changed?)");
            return p;
        }

        private static void SetRef(SerializedObject so, string name, Object value, Report report, bool overwrite)
        {
            SerializedProperty p = Find(so, name, report);
            if (p == null || p.objectReferenceValue == value) return;
            if (!overwrite && p.objectReferenceValue != null) return;   // a human (or earlier run) already chose
            p.objectReferenceValue = value;
            report.Change($"{so.targetObject.GetType().Name}.{name}");
        }

        private static void SetEnum(SerializedObject so, string name, int value, Report report)
        {
            SerializedProperty p = Find(so, name, report);
            if (p == null || p.intValue == value) return;
            p.intValue = value;   // intValue = the enum's numeric value (enumValueIndex would be the declaration index)
            report.Change($"{so.targetObject.GetType().Name}.{name}");
        }

        private static void SetInt(SerializedObject so, string name, int value, Report report) =>
            SetEnum(so, name, value, report);

        private static void SetBool(SerializedObject so, string name, bool value, Report report)
        {
            SerializedProperty p = Find(so, name, report);
            if (p == null || p.boolValue == value) return;
            p.boolValue = value;
            report.Change($"{so.targetObject.GetType().Name}.{name}");
        }

        private static void SetString(SerializedObject so, string name, string value, Report report)
        {
            SerializedProperty p = Find(so, name, report);
            if (p == null || p.stringValue == value) return;
            p.stringValue = value;
            report.Change($"{so.targetObject.GetType().Name}.{name}");
        }

        /// <summary>Collects what a run changed so each run prints one summary line.</summary>
        private sealed class Report
        {
            private readonly List<string> _changes = new List<string>();
            private readonly List<string> _errors = new List<string>();

            public int Changes => _changes.Count;
            public int Errors => _errors.Count;

            public void Change(string what) => _changes.Add(what);
            public void Error(string what) => _errors.Add(what);

            public string Summary()
            {
                string text = _changes.Count == 0 ? "already wired, 0 changes" :
                    $"{_changes.Count} change(s): {string.Join(", ", _changes)}";
                if (_errors.Count > 0)
                {
                    text += $" | {_errors.Count} ERROR(S): {string.Join("; ", _errors)}";
                    Debug.LogError($"[F-03c] {string.Join("; ", _errors)}");
                }
                return text;
            }
        }
    }
